#!/usr/bin/env bash
# Builds release archives for the common platforms into dist/ and writes SHA256SUMS.
# Nothing in the source tree is modified; the version is injected with -ldflags.
#
#   scripts/dist.sh                  # version from git (git describe)
#   VERSION=1.2.3 scripts/dist.sh
#
# Output per platform: foundry_<version>_<os>_<arch>.tar.gz (.zip for Windows), containing the binary,
# LICENSE and README.md. With dpkg-deb available, .deb packages for linux/amd64 and linux/arm64 as well.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
MODULE="github.com/SandSoftwareSolutions/Foundry"
VERSION="${VERSION:-$(git describe --tags --always --dirty 2>/dev/null | sed 's/^v//' || echo dev)}"
COMMIT="${COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo none)}"
DATE="${DATE:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}"
LDFLAGS="-s -w -X $MODULE/internal/cli.version=$VERSION -X $MODULE/internal/cli.commit=$COMMIT -X $MODULE/internal/cli.date=$DATE"
OUT="$ROOT/dist"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT"

TARGETS=(linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64)

for target in "${TARGETS[@]}"; do
  os="${target%/*}"; arch="${target#*/}"
  name="foundry_${VERSION}_${os}_${arch}"
  dir="$WORK/$name"
  mkdir -p "$dir"
  bin="foundry"; [ "$os" = windows ] && bin="foundry.exe"
  echo "[build] $os/$arch"
  CGO_ENABLED=0 GOOS="$os" GOARCH="$arch" go build -trimpath -ldflags "$LDFLAGS" -o "$dir/$bin" ./cmd/foundry
  cp LICENSE README.md "$dir/"
  if [ "$os" != windows ]; then cp scripts/install.sh "$dir/install.sh"; fi
  if [ "$os" = windows ]; then
    if command -v zip >/dev/null 2>&1; then
      (cd "$WORK" && zip -qr "$OUT/$name.zip" "$name")
    else
      python3 -c 'import shutil, sys; shutil.make_archive(sys.argv[1], "zip", sys.argv[2], sys.argv[3])' "$OUT/$name" "$WORK" "$name"
    fi
  else
    tar -C "$WORK" -czf "$OUT/$name.tar.gz" "$name"
  fi
done

if command -v dpkg-deb >/dev/null 2>&1; then
  for arch in amd64 arm64; do
    pkg="$WORK/deb-$arch"
    mkdir -p "$pkg/DEBIAN" "$pkg/usr/bin"
    cp "$WORK/foundry_${VERSION}_linux_${arch}/foundry" "$pkg/usr/bin/foundry"
    chmod 755 "$pkg/usr/bin/foundry"
    # Shell completions, generated by the program itself. The amd64 binary is the one that can run on the build
    # machine; the text is the same for arm64.
    host="$WORK/foundry_${VERSION}_linux_amd64/foundry"
    if "$host" version >/dev/null 2>&1; then
      mkdir -p "$pkg/usr/share/bash-completion/completions" "$pkg/usr/share/zsh/vendor-completions" "$pkg/usr/share/fish/vendor_completions.d"
      "$host" completion bash > "$pkg/usr/share/bash-completion/completions/foundry"
      "$host" completion zsh > "$pkg/usr/share/zsh/vendor-completions/_foundry"
      "$host" completion fish > "$pkg/usr/share/fish/vendor_completions.d/foundry.fish"
    else
      echo "[warn] cannot run the linux/amd64 binary here; the .deb gets no shell completions"
    fi
    cat > "$pkg/DEBIAN/control" <<CONTROL
Package: foundry
Version: ${VERSION#v}
Section: devel
Priority: optional
Architecture: $arch
Maintainer: Sand Software Solutions <info@sandsoftwaresolutions.nl>
Description: Create new projects from your own templates
 Foundry saves directories as templates and scaffolds new projects from them,
 with placeholders, ignore rules and a first git commit.
CONTROL
    dpkg-deb --root-owner-group --build "$pkg" "$OUT/foundry_${VERSION}_${arch}.deb" >/dev/null
    echo "[deb] foundry_${VERSION}_${arch}.deb"
  done
else
  echo "[skip] dpkg-deb not found, no .deb packages"
fi

(cd "$OUT" && : > SHA256SUMS && for f in *.tar.gz *.zip *.deb; do [ -e "$f" ] && sha256sum "$f" >> SHA256SUMS; done; true)
echo "Done. Artifacts and SHA256SUMS are in $OUT"
